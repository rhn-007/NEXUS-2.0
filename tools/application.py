"""Launch approved Windows applications and open approved folders."""

import logging
import os
import subprocess
from pathlib import Path

from tools.base import BaseTool
from tools.response import ToolResponse


logger = logging.getLogger(__name__)


class ApplicationTool(BaseTool):
    name = "application"
    description = "Launches approved Windows applications and opens approved folders."

    def __init__(self):
        self.applications = {
            "spotify": {
                "id": "SpotifyAB.SpotifyMusic_zpdnekdrzrea0!Spotify",
                "aliases": ["spotify"]
            },
            "calculator": {
                "id": "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App",
                "aliases": ["calculator", "calc"]
            },
            "whatsapp": {
                "id": "5319275A.WhatsAppDesktop_cv1g1gvanyjgm!App",
                "aliases": ["whatsapp", "whatsapp desktop", "whatsapp application"]
            },
            "opera": {
                "path": str(
                    Path.home()
                    / "AppData"
                    / "Local"
                    / "Programs"
                    / "Opera"
                    / "opera.exe"
                ),
                "aliases": ["opera", "opera browser"]
            },
            "idle": {
                "id": "Microsoft.AutoGenerated.{1E153123-6685-C36C-F1A3-38525D1AC378}",
                "aliases": ["idle", "python idle", "idle script", "python"]
            },
            "notepad": {
                "id": "Microsoft.WindowsNotepad_8wekyb3d8bbwe!App",
                "aliases": ["notepad"]
            },
            "word": {
                "id": "Microsoft.Office.WINWORD.EXE.15",
                "aliases": ["word", "microsoft word"]
            },
            "excel": {
                "id": "Microsoft.Office.EXCEL.EXE.15",
                "aliases": ["excel", "microsoft excel"]
            }
        }

        self.folders = {
            "files and docs": Path.home() / "OneDrive" / "files and docs",
            "documents": Path.home() / "Documents",
            "downloads": Path.home() / "Downloads"
        }

        self.launch_phrases = ("open", "launch", "start", "run")

    def can_handle(self, query):
        if not query:
            return False

        text = query.lower().strip()

        if not any(
            text.startswith(phrase + " ")
            for phrase in self.launch_phrases
        ):
            return False

        for app in self.applications.values():
            if any(alias in text for alias in app["aliases"]):
                return True

        if any(folder in text for folder in self.folders):
            return True

        return "file explorer" in text or "explorer" in text

    def execute(self, query):
        text = query.lower().strip()

        try:
            for folder_name, folder_path in self.folders.items():
                if folder_name in text:
                    return self.open_folder(folder_name, folder_path)

            if "file explorer" in text or "explorer" in text:
                return self.open_file_explorer()

            for app_name, app_info in self.applications.items():
                if any(alias in text for alias in app_info["aliases"]):
                    if app_name == "opera":
                        return self.open_opera(app_info["path"])

                    return self.open_application(
                        app_name,
                        app_info["id"]
                    )

            return ToolResponse.failure(
                "I couldn't identify the application or folder."
            )

        except Exception as error:
            logger.exception("Application control error")
            return ToolResponse.failure(
                f"I couldn't complete that action: {error}"
            )

    def open_opera(self, opera_path):
        if not Path(opera_path).exists():
            return ToolResponse.failure(
                "I couldn't find the Opera executable."
            )

        try:
            subprocess.Popen([opera_path], shell=False)
            logger.info("Launched Opera.")
            return ToolResponse.success("Opening Opera.")
        except Exception as error:
            logger.exception("Could not launch Opera")
            return ToolResponse.failure(
                f"I couldn't open Opera: {error}"
            )

    def open_application(self, name, app_id):
        try:
            subprocess.Popen(
                ["explorer.exe", f"shell:AppsFolder\\{app_id}"],
                shell=False
            )
            logger.info("Launched application: %s", name)
            return ToolResponse.success(
                f"Opening {name.title()}."
            )
        except Exception as error:
            logger.exception("Could not launch %s", name)
            return ToolResponse.failure(
                f"I couldn't open {name.title()}: {error}"
            )

    def open_folder(self, name, path):
        if not path.exists():
            return ToolResponse.failure(
                f"The {name} folder could not be found."
            )

        try:
            os.startfile(str(path))
            logger.info("Opened folder: %s", path)
            return ToolResponse.success(
                f"Opening your {name} folder."
            )
        except Exception as error:
            logger.exception("Could not open folder: %s", path)
            return ToolResponse.failure(
                f"I couldn't open your {name} folder: {error}"
            )

    def open_file_explorer(self):
        try:
            subprocess.Popen(["explorer.exe"], shell=False)
            logger.info("Opened File Explorer.")
            return ToolResponse.success("Opening File Explorer.")
        except Exception as error:
            logger.exception("Could not open File Explorer")
            return ToolResponse.failure(
                f"I couldn't open File Explorer: {error}"
            )
