
"""
NEXUS Application Control Tool

Launches registered Windows applications
and opens approved folders.
"""

import os
import subprocess
import logging

from pathlib import Path

from tools.base import BaseTool


logger = logging.getLogger(__name__)


class ApplicationTool(BaseTool):

    name = "application"

    description = (
        "Launches Windows applications and opens approved folders."
    )

    def __init__(self):

        self.applications = {

            "spotify": {
                "id": "SpotifyAB.SpotifyMusic_zpdnekdrzrea0!Spotify",
                "aliases": ["spotify"]
            },

            "calculator": {
                "id": "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App",
                "aliases": ["calculator", "calc"]
            },

            "whatsapp": {
                "id": "5319275A.WhatsAppDesktop_cv1g1gvanyjgm!App",
                "aliases": ["whatsapp", "whatsapp desktop", "whatsapp application"]
            },

            "opera": {
                "path": str(
                    Path.home()
                    / "AppData"
                    / "Local"
                    / "Programs"
                    / "Opera"
                    / "opera.exe"
                ),
                "aliases": ["opera", "opera browser"]
            },

            "idle": {
                "id": "Microsoft.AutoGenerated.{1E153123-6685-C36C-F1A3-38525D1AC378}",
                "aliases": ["idle", "python idle", "idle script", "python"]
            },

            "notepad": {
                "id": "Microsoft.WindowsNotepad_8wekyb3d8bbwe!App",
                "aliases": ["notepad"]
            },

            "word": {
                "id": "Microsoft.Office.WINWORD.EXE.15",
                "aliases": ["word", "microsoft word"]
            },

            "excel": {
                "id": "Microsoft.Office.EXCEL.EXE.15",
                "aliases": ["excel", "microsoft excel"]
            }

        }

        self.folders = {

            "files and docs": (
                Path.home()
                / "OneDrive"
                / "files and docs"
            ),

            "documents": (
                Path.home()
                / "Documents"
            ),

            "downloads": (
                Path.home()
                / "Downloads"
            )

        }

        self.launch_phrases = [
            "open",
            "launch",
            "start",
            "run"
        ]

    def can_handle(self, query):

        if not query:
            return False

        text = query.lower().strip()

        if not any(
            text.startswith(phrase + " ")
            for phrase in self.launch_phrases
        ):
            return False

        for app in self.applications.values():
            for alias in app["aliases"]:
                if alias in text:
                    return True

        for folder in self.folders:
            if folder in text:
                return True

        if "file explorer" in text or "explorer" in text:
            return True

        return False

    def execute(self, query):

        text = query.lower().strip()

        try:

            for folder_name, folder_path in self.folders.items():
                if folder_name in text:
                    return self.open_folder(folder_name, folder_path)

            if "file explorer" in text or "explorer" in text:
                return self.open_file_explorer()

            for app_name, app_info in self.applications.items():
                for alias in app_info["aliases"]:
                    if alias in text:

                        if app_name == "opera":
                            return self.open_opera(app_info["path"])

                        return self.open_application(
                            app_name,
                            app_info["id"]
                        )

            return "I couldn't identify the application or folder."

        except Exception as e:

            logger.error(f"Application control error: {e}")
            return f"I couldn't complete that action: {e}"

    def open_opera(self, opera_path):

        try:

            if not Path(opera_path).exists():
                return "I couldn't find the Opera executable."

            subprocess.Popen([opera_path], shell=False)

            logger.info("Launched Opera.")
            return "Opening Opera."

        except Exception as e:

            logger.error(f"Could not launch Opera: {e}")
            return f"I couldn't open Opera: {e}"

    def open_application(self, name, app_id):

        try:

            subprocess.Popen(
                [
                    "explorer.exe",
                    f"shell:AppsFolder\\{app_id}"
                ],
                shell=False
            )

            logger.info(f"Launched application: {name}")
            return f"Opening {name.title()}."

        except Exception as e:

            logger.error(f"Could not launch {name}: {e}")
            return f"I couldn't open {name.title()}: {e}"

    def open_folder(self, name, path):

        if not path.exists():
            return f"The {name} folder could not be found."

        try:

            os.startfile(str(path))

            logger.info(f"Opened folder: {path}")
            return f"Opening your {name} folder."

        except Exception as e:

            logger.error(f"Could not open folder {path}: {e}")
            return f"I couldn't open your {name} folder: {e}"

    def open_file_explorer(self):

        try:

            subprocess.Popen(["explorer.exe"], shell=False)

            logger.info("Opened File Explorer.")
            return "Opening File Explorer."

        except Exception as e:

            logger.error(f"Could not open File Explorer: {e}")
            return f"I couldn't open File Explorer: {e}"
